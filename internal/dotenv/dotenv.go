package dotenv

import "strings"

// KeyValue is one parsed environment entry.
type KeyValue struct {
	Key   string
	Value string
}

// Parse returns duplicate keys in order for the caller to resolve; lines without `=` are ignored.
func Parse(content string) []KeyValue {
	var out []KeyValue
	for _, raw := range strings.Split(content, "\n") {
		line := strings.TrimSpace(strings.TrimSuffix(raw, "\r"))
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		line = strings.TrimPrefix(line, "export ")
		key, value, ok := strings.Cut(line, "=")
		if !ok {
			continue
		}
		key = strings.TrimSpace(key)
		if key == "" {
			continue
		}
		out = append(out, KeyValue{Key: key, Value: unquote(strings.TrimSpace(value))})
	}
	return out
}

func unquote(v string) string {
	if len(v) >= 2 {
		if (v[0] == '"' && v[len(v)-1] == '"') || (v[0] == '\'' && v[len(v)-1] == '\'') {
			return v[1 : len(v)-1]
		}
	}
	return v
}
